#!/usr/bin/env python3
"""Проверяет перевод: сохранилось ли то, за что цепляется механика страницы.

    python3 tools/check-i18n.py

Перевод портит не текст, а **связь текста с механикой вокруг него**. Абзац
может быть переведён безупречно и при этом перестать работать: подстрочник
потеряет слово, фильтр словаря перестанет находить статью, поиск не найдёт
термин. Страница при этом выглядит целой — этим и опасно.

Отсюда правило, по которому написаны все проверки ниже: **где механика
цепляется за текст, там же и проверка.** Что ни с чем не связано — например,
название книги в прозе, — проверить нечем, и делать вид, что проверено, не
надо.

Проверяется семь вещей:

1. **Транслитерация в словарях не тронута.** Одно и то же слово стоит в статье
   дважды: в `data-tts="citi"` — внутри тега, а тег маскируется целиком и до
   модели не доходит, — и текстом в столбце «Санскрит», куда модель смотрит.
   Сличается **пара из перевода с парой из исходника**, а не половинки между
   собой: в словаре «Натьяшастры» они и по-русски разные — там `data-tts` это
   имя звукового файла, с которого диакритика снята нарочно. Проверять надо
   «не изменилось ли», а не «одинаково ли»; первая же попытка перепутала это и
   выдала 422 расхождения на ровном месте.
2. **Пометы целы — там, где на них что-то держится.** Последовательность
   санскритских помет в скобках должна совпасть с исходной: из них собирается
   подстрочник. Но собирается он только на страницах писаний; на рукописных
   скобка — обычная скобка, и добавленная моделью «(movements)» там ничего не
   ломает. Поэтому расхождения показываются везде, а роняют проверку только
   там, где подстрочник и правда есть, — то есть в **куске**, а не на
   странице: подпись под гимном стоит на той же странице, что и строфы, но
   скобка в ней — просто скобка.
3. **Разметка цела.** Ссылок, разделителей таблицы и полужирных — поровну.

   И не только числом. Теги можно вернуть все до одного и при этом
   **переставить их относительно текста**: слово, стоявшее внутри тега,
   оказывается снаружи, а тег — пустым. Так на английских гимнах
   Śivastotrāvalī санскритское слово уехало из своей ссылки
   (`<rt>ātmā<a class="pv-gl"></a></rt>` вместо `<rt><a …>ātmā</a></rt>`):
   ссылки не видно и не нажать, подстрочник разъехался. Так же в английском
   словаре Pratyabhijñāhṛdayam толкование уехало из своей ячейки (VS-53).
   Считать теги тут бесполезно — их поровну; сличается, **в каких промежутках
   между тегами стояло слово**, а в каких не стояло. Промежутков на странице
   тысячи, и расстановка эта — то самое, за что цепляется вёрстка.
4. **Ничего не осталось по-русски.** Кусок, который конвейер отверг, он
   оставляет русским нарочно — лучше по-русски, чем испорченным. Но знать,
   сколько таких, надо.

   Считается при этом **проза, а не разметка**. Кириллица бывает двух родов, и
   одним числом они не меряются: русское слово в тексте — отвергнутый кусок, а
   русское слово внутри тега (`data-alias="санкоча"`, `title="Афоризм 4"`,
   `placeholder="начните вводить термин"`) переводом не было тронуто и тронуто
   быть не могло — тег маскируется целиком и до модели не доходит. Пока
   считалось всё подряд, семь десятков безупречно переведённых кусков словаря
   числились непереведёнными и прятали за собой настоящие. Второе число
   показывается отдельно: это не поломка перевода, а то, до чего перевод не
   дотягивается вовсе.
5. **У каждой английской страницы есть русская.** Иначе перевод пережил
   страницу, которой больше нет.
6. **Front matter доехал.** Всё, что страница объявила о себе сверх заголовка —
   `layout`, `search`, что угодно, — обязано стоять и у двойника. Это самая
   тихая из здешних поломок: страница собирается, открывается и читается, и
   только механика, за которую цеплялось потерянное поле, не работает.
   Английская страница пожертвований так потеряла `layout: donate`, а с ним и
   кнопки копирования крипто-адресов — адреса остались на ней текстом. Проза во
   front matter (`description`) сличается наличием, а не значением: она
   переводится, как и заголовок.

7. **Ссылки с английской страницы ведут на английские.** Там, где двойник
   есть: где его нет, ссылка честно остаётся русской — страница и правда
   русская, и подменять её нечем. Исключение одно, и оно нарочное: обратный
   адрес самой страницы (`ru:`). У заместителя это половина его смысла — «та
   русская страница, за которой вы шли, никуда не делась».

   Проверка нужна оттого, что подменяет ссылки не человек, а `relink()` в
   `tools/translate.py`, и промахивается он молча: страница собирается,
   ссылка работает, читатель просто оказывается в русском тексте. Сличая
   адреса строка в строку, он не узнавал двойника у адреса, написанного без
   косой черты в конце, — и уводил в русское дерево с 82 ссылок, включая все
   девять разделов на английской главной.

Заодно показывается заголовок, оставшийся русским. Русский заголовок на
английской странице — это не поломка, а честный отказ конвейера: перевод не
дался, и по-русски он хотя бы не врёт. Но знать, сколько таких, надо.

Страницы-заместители (те, у кого во front matter стоит `source:`) проверяются
иначе, и по тому же правилу. Своего текста у них нет — сличать нечего; вся их
работа держится на двух ссылках: на подлинник у источника и на русскую
страницу, за которой читатель шёл. Их и проверяем.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EN = os.path.join(ROOT, 'en')

CYR = re.compile(r'[А-Яа-яЁё]')
# Та же помета, что маскируется при переводе (см. KEEP в common/translate.py).
MARK = re.compile(r'\([A-Za-zĀ-ſḀ-ỿ\'\-\s.…|]+\)')
# Всё, что стоит в скобках. Теги снимаются: в подстрочнике скобка разорвана
# разметкой пополам — `<ruby>слово<rp> (</rp><rt>…`.
TAG = re.compile(r'<[^>]+>')
GROUP = re.compile(r'\(([^()]*)\)')
ROW = re.compile(r'data-tts="([^"]+)"[^>]*>([^<]*)</td>')
LINK = re.compile(r'\]\((?:/|https?://)[^)]*\)')
SOURCE = re.compile(r'^source:\s*(\S+)\s*$', re.M)
# Английская пара, написанная руками. Не перевод — сличать построчно нечего:
# ссылок, помет и полужирных у неё столько, сколько нужно ей самой.
BYHAND = re.compile(r'^byhand:\s*true\s*$', re.M)
RU = re.compile(r'^ru:\s*(\S+)\s*$', re.M)
# Строка front matter. Front matter на этом сайте плоский: продолжений и
# вложенности не бывает ни на одной странице.
FMLINE = re.compile(r'^([A-Za-z_][\w-]*):\s*(.*)$')
# Поля, которые двойнику принадлежат по праву: заголовок конвейер переводит,
# язык объявляет, обратный адрес считает, а `source` и `byhand` ставит
# страницам, у которых своего текста нет. Сличать их с исходником нечего — там
# их и не было. Всё остальное, `search` в том числе, — своё у страницы и
# обязано доехать.
MINE = ('title', 'lang', 'ru', 'source', 'byhand')
# Проза: переводится, а не переносится. Сличается наличием.
PROSE = ('description',)
TITLE = re.compile(r'^title:\s*"?(.*?)"?\s*$', re.M)
# Адрес внутрь сайта: из разметки Markdown и из готового тега. Перечни глав на
# заглавных написаны прямо на HTML, и там ссылка выглядит вторым образом.
INSIDE = re.compile(r'\]\((/[^)\s]*)\)|href="(/[^"]*)"')
# Разметка, внутрь которой перевод не заглядывает: тег целиком и вставки
# Jekyll. То же самое маскируется при переводе (KEEP в common/translate.py).
MARKUP = re.compile(r'<[^>]+>|\{%.*?%\}|\{\{.*?\}\}', re.S)
BOLD = re.compile(r'\*\*')
CELL = re.compile(r'</t[dh]>')
# Буква или цифра: по ним и решается, стояло ли в промежутке между тегами
# слово. Знаки препинания и пробелы не в счёт — тире по краям пояснения и
# точка-разделитель переезжают при переводе законно (EDGE в translate.py).
WORDCH = re.compile(r'[^\W_]', re.U)


# Кусок, в котором из скобок строится подстрочник: слово по-русски, санскрит
# над ним. Разметка эта ставится при сборке страницы (`tools/common/page.py`),
# а не рисуется скриптом, и потому видна прямо в исходнике.
RUBY = ('pv-tr', 'pv-pair', '<ruby')


def interlinear(text):
    """Только те куски страницы, где подстрочник и правда есть."""
    return '\n\n'.join(b for b in re.split(r'\n\s*\n', text)
                       if any(w in b for w in RUBY))


def moved(en, ru):
    """Разъехались ли пометы: потерялась, прибавилась или переехала.

    Сличаются **все** скобки по порядку, а не одни пометы. Скобка здесь бывает
    двух родов, и по-русски их различает алфавит: латиница — санскрит соседнего
    слова, кириллица — слово, вставленное переводчиком для связности (`_(и)_`,
    `_(преданным)_`). Помета обязана доехать неизменной; вставленное слово
    обязано перевестись — оно затем и вставлено, чтобы его читали. Правило то
    же, что в `moved()` из tools/translate.py, и по той же причине: проверка
    сличает ровно то, что конвейер обещает.
    """
    a, b = GROUP.findall(TAG.sub('', ru)), GROUP.findall(TAG.sub('', en))
    if len(a) != len(b):
        return True
    return any(x != y for x, y in zip(a, b) if MARK.fullmatch('(%s)' % x))


def spread(text):
    """Где между тегами стоит слово, а где нет.

    Ответ — по одному «да/нет» на каждый промежуток. Перевод меняет слова, но
    не вправе менять их расстановку по разметке: где в исходнике внутри тега
    стояло слово, там оно обязано остаться, а пустое место обязано остаться
    пустым. Переехавшее через тег слово оставляет страницу целой на вид —
    теги все на месте, текст весь на месте, — и потому не ловится ничем, кроме
    этого.

    Написано здесь, а не взято из `tools/translate.py`, по тому же правилу, по
    которому здесь же повторён `moved()`: проверка сличает то, что конвейер
    обещает, и обязана делать это своими руками.
    """
    return tuple(bool(WORDCH.search(g)) for g in MARKUP.split(text))


def gaps(text):
    """Промежутки между тегами вместе с тегом, что стоит перед каждым."""
    out, at = [], 0
    for m in MARKUP.finditer(text):
        out.append((text[at:m.start()], m.group(0)))
        at = m.end()
    out.append((text[at:], ''))
    return out


def frontmatter(text):
    """Front matter страницы: имя поля → значение. Нет его — пусто."""
    m = re.match(r'\A---\n(.*?)\n---\n', text, re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).split('\n'):
        f = FMLINE.match(line)
        if f:
            out[f.group(1)] = f.group(2).strip()
    return out


def twin_of(url):
    """Файл английского двойника для адреса русской страницы. Нет его — None."""
    u = url.split('#')[0].split('?')[0].rstrip('/').lstrip('/')
    for cand in (os.path.join(EN, u + '.md'), os.path.join(EN, u, 'index.md')):
        if os.path.exists(cand):
            return cand
    return None


def pairs():
    """(английская страница, её русский исходник)."""
    out = []
    for base, dirs, files in os.walk(EN):
        for f in sorted(files):
            if f.endswith('.md'):
                en = os.path.relpath(os.path.join(base, f), EN)
                out.append((en, os.path.join(ROOT, en)))
    return out


def main():
    bad = 0
    rows = pairs()
    if not rows:
        print('в /en/ ничего нет — сперва python3 tools/translate.py')
        return 1

    lost_pages, missing, tts_bad, mark_bad, mark_soft, markup_bad = [], [], [], [], [], []
    stubs, stub_bad, ru_title, byhand, fm_bad, link_bad = [], [], [], [], [], []
    shifted, frame_bad = [], []
    in_markup = 0
    for en_rel, ru_path in rows:
        en_path = os.path.join(EN, en_rel)
        en = open(en_path, encoding='utf-8').read()
        if not os.path.exists(ru_path):
            missing.append(en_rel)
            continue
        ru = open(ru_path, encoding='utf-8').read()

        # 7. Ссылки. Проверяются у всех подряд — и у перевода, и у
        # заместителя, и у написанной руками: увести в русский текст с
        # английской страницы может любая. Исключение одно — обратный адрес
        # самой страницы.
        back = RU.search(en)
        back = back.group(1) if back else None
        for m in INSIDE.finditer(en):
            u = m.group(1) or m.group(2)
            if u.startswith('/en/') or u == back:
                continue
            if twin_of(u):
                link_bad.append((en_rel, u))

        # Написанная руками: не перевод, а пара. Проверки ниже мерят, что
        # уцелело от исходника при переводе, и к ней неприменимы все до одной.
        if BYHAND.search(en[:en.index('---', 4)] if '---' in en[4:] else en):
            byhand.append(en_rel)
            continue

        # Страница-заместитель: текста нет, есть две ссылки, и обе обязаны быть
        # на месте. Пропала ссылка на подлинник — страница стала тупиком;
        # пропала ссылка на русскую — читатель, шедший за главой, её не найдёт.
        src = SOURCE.search(en)
        if src:
            stubs.append(en_rel)
            back = RU.search(en)
            if src.group(1) not in en[src.end():]:
                stub_bad.append((en_rel, 'нет ссылки на подлинник'))
            if not back:
                stub_bad.append((en_rel, 'нет обратного адреса'))
            elif '](%s)' % back.group(1) not in en:
                stub_bad.append((en_rel, 'нет ссылки на русскую страницу'))
            t = TITLE.search(en[:en.index('---', 4)] if '---' in en[4:] else en)
            if t and CYR.search(t.group(1)):
                ru_title.append((en_rel, t.group(1)))
            continue

        # 0. Front matter: что страница объявила о себе, то объявляет и двойник.
        was, now = frontmatter(ru), frontmatter(en)
        for name, value in was.items():
            if name in MINE:
                continue
            if name not in now:
                fm_bad.append((en_rel, name, 'потерялось: ' + value))
            elif name not in PROSE and now[name] != value:
                fm_bad.append((en_rel, name, 'было «%s», стало «%s»' % (value, now[name])))
        t = now.get('title')
        if t and CYR.search(t):
            ru_title.append((en_rel, t.strip('"')))

        # 1. Транслитерация: пара из перевода против пары из исходника.
        was = dict(ROW.findall(ru))
        for tts, shown in ROW.findall(en):
            if tts in was and shown.strip() != was[tts].strip():
                tts_bad.append((en_rel, tts, was[tts].strip(), shown.strip()))

        # 2. Пометы. Роняют проверку только там, где из них строится
        # подстрочник, — и подстрочник ищется в **куске**, а не на странице.
        # Под каждым гимном Śivastotrāvalī стоит подпись «Санскрит (деванагари
        # и IAST) перенесён без изменений…», и её перевод честно даёт
        # «(Devanāgarī and IAST)» — скобку, которой в русском не было только
        # потому, что внутри неё стояла кириллица. Подписи подстрочником не
        # строят; строфы над ними строят, и живут они на одной странице. Пока
        # считалось по странице, безупречный перевод двадцати подписей числился
        # поломкой — а `tools/translate.py` из-за этого оставлял их русскими.
        a, b = MARK.findall(ru), MARK.findall(en)
        if a != b:
            at = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            row = (en_rel, len(a), len(b),
                   a[at] if at < len(a) else '—', b[at] if at < len(b) else '—')
            (mark_bad if moved(interlinear(en), interlinear(ru))
             else mark_soft).append(row)

        # 3. Разметка. Ссылки и ячейки обязаны совпасть числом: потерянная
        # ссылка — потерянная страница, потерянная ячейка — разъехавшаяся
        # таблица. С полужирным иначе: важно не «столько же», а «парно».
        # Непарная звёздочка выводит на страницу саму себя; лишняя пара —
        # только вопрос вкуса.
        for pat, what in ((LINK, 'ссылок'), (CELL, 'ячеек')):
            x, y = len(pat.findall(ru)), len(pat.findall(en))
            if x != y:
                markup_bad.append((en_rel, what, x, y))
        # Сличается **чётность до и после**, а не сама чётность: на
        # `art/index.md` звёздочка непарна и по-русски, и перевод тут ни при
        # чём. Проверять надо «не испортил ли перевод», а не «хорошо ли
        # написано».
        x, y = len(BOLD.findall(ru)), len(BOLD.findall(en))
        if x % 2 != y % 2:
            markup_bad.append((en_rel, 'звёздочка потерялась', x, y))

        # 3б. Расстановка текста по разметке. Теги можно вернуть все и при этом
        # переставить их относительно текста: слово уезжает из тега наружу, тег
        # остаётся пустым, и число тегов при этом не меняется — считать их
        # бесполезно. Сличается, в каких промежутках между тегами стояло слово.
        was_body = re.sub(r'\A---\n.*?\n---\n', '', ru, flags=re.S)
        now_body = re.sub(r'\A---\n.*?\n---\n', '', en, flags=re.S)
        a, b = spread(was_body), spread(now_body)
        if len(a) != len(b):
            # Разметки не столько же — сличать расстановку не по чему. Само по
            # себе это расхождение: перевод отстал от страницы, которую
            # переводил, либо потерял разметку целиком.
            frame_bad.append((en_rel, len(a) - 1, len(b) - 1))
        elif a != b:
            at = next(i for i, (x, y) in enumerate(zip(a, b)) if x != y)
            here = gaps(was_body)[at]
            there = gaps(now_body)[at]
            shifted.append((en_rel, sum(1 for x, y in zip(a, b) if x != y),
                            (here[0].strip() or '—')[:28],
                            (there[0].strip() or '—')[:28], there[1][:40]))

        # 4. Осталось по-русски — в прозе. Кириллица внутри тега считается
        # отдельно: там она не перевода недоделка, а то, чего перевод не видит.
        body = re.sub(r'\A---\n.*?\n---\n', '', en, flags=re.S)
        left = [b for b in re.split(r'\n\s*\n', body) if CYR.search(b)]
        prose = [b for b in left if CYR.search(MARKUP.sub('', b))]
        in_markup += len(left) - len(prose)
        if prose:
            lost_pages.append((en_rel, len(prose)))

    print('страниц переведено: %d, из них со ссылкой на подлинник: %d, '
          'написано руками: %d' % (len(rows), len(stubs), len(byhand)))

    print('\nу заместителя порвана ссылка: %d' % len(stub_bad))
    for rel, why in stub_bad[:20]:
        print('   %-34s %s' % (rel, why))

    print('\nссылка уводит в русское дерево, хотя двойник есть: %d' % len(link_bad))
    for rel, u in link_bad[:20]:
        print('   %-34s %s' % (rel, u))

    print('\nfront matter не доехал: %d' % len(fm_bad))
    for rel, name, why in fm_bad[:20]:
        print('   %-34s %s: %s' % (rel, name, why))

    print('\nзаголовок остался русским: %d' % len(ru_title))
    for rel, t in ru_title[:10]:
        print('   %-34s %s' % (rel, t))

    print('\nбез русского исходника: %d' % len(missing))
    for x in missing:
        print('   %s' % x)

    print('\nтранслитерация тронута: %d' % len(tts_bad))
    for rel, tts, was, now in tts_bad[:20]:
        print('   %-30s %s: было «%s», стало «%s»' % (rel, tts, was, now))

    print('\nпометы разошлись там, где на них держится подстрочник: страниц %d'
          % len(mark_bad))
    for rel, x, y, a, b in mark_bad[:20]:
        print('   %-34s было %d, стало %d; первое: «%s» → «%s»' % (rel, x, y, a, b))

    print('\nскобки прибавились там, где они просто скобки: страниц %d, всего %d'
          % (len(mark_soft), sum(y - x for _r, x, y, _a, _b in mark_soft if y > x)))
    for rel, x, y, _a, b in sorted(mark_soft, key=lambda r: r[1] - r[2])[:8]:
        print('   %-34s было %d, стало %d; например «%s»' % (rel, x, y, b))

    print('\nразметка разошлась: %d' % len(markup_bad))
    for rel, what, x, y in markup_bad[:20]:
        print('   %-34s %s: было %d, стало %d' % (rel, what, x, y))

    print('\nтекст переехал через тег — где стояло слово, там пусто: страниц %d, '
          'мест %d' % (len(shifted), sum(n for _r, n, _a, _b, _t in shifted)))
    for rel, n, was, now, tag in sorted(shifted, key=lambda r: -r[1])[:20]:
        print('   %-30s мест %2d; первое: было «%s», стало «%s» перед %s'
              % (rel, n, was, now, tag))

    print('\nразметки не столько же — расстановку сличать не по чему: %d'
          % len(frame_bad))
    for rel, x, y in frame_bad[:20]:
        print('   %-34s тегов было %d, стало %d' % (rel, x, y))

    print('\nкириллица внутри разметки, куда перевод не заглядывает: кусков %d'
          % in_markup)

    print('\nосталось по-русски: страниц %d, кусков %d'
          % (len(lost_pages), sum(n for _, n in lost_pages)))
    for rel, n in sorted(lost_pages, key=lambda x: -x[1])[:10]:
        print('   %-34s %d' % (rel, n))

    bad = (len(missing) + len(tts_bad) + len(mark_bad) + len(markup_bad)
           + len(stub_bad) + len(fm_bad) + len(link_bad)
           + len(shifted) + len(frame_bad))
    print('\n%s' % ('расхождений нет' if not bad else 'расхождений: %d' % bad))
    return 1 if bad else 0


