#!/usr/bin/env python3
"""Чем «Тантрасара» отличается от прочих писаний источника.

Главное отличие одно, и оно меняет весь конвейер: русский перевод у источника
уже есть, и целиком. Здесь не переводят — переносят. Поэтому `ru/*.json` у
этого конвейера нет вовсе: перевод приходит вместе с блоками, и переведённым
блок признаётся по кириллице в нём.

Пометка `pv-en` при этом никуда не делась. Она осталась ровно для того, для
чего заведена: если у источника какой-то абзац остался по-английски, он и
здесь будет стоять по-английски и в рамке, а не выдаваться за русский.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
sys.path.insert(0, HERE)

from common.page import Book, plural
from parts import PARTS, SRC, SRC_URL

GLOSSARY = '/ksh/tantrasara/glossary/'

CYR = re.compile(r'[А-Яа-яЁё]')

# Заголовок главы на деванагари: «तन्त्रसारः / <порядковое>माह्निकम्».
TITLE = re.compile(r'^तन्त्रसारः\n\S*माह्निकम्$')


def dedup_title(bs):
    """Заголовок главы на деванагари, стоящий у источника дважды.

    В 6-й главе он повторён слово в слово, в 10-й первым стоит заголовок 9-й
    («नवममाह्निकम्» вместо «दशममाह्निकम्») — обе описки одного рода. Стена
    транслитерации при этом заголовок содержит один, и складывание стен
    обрывалось на второй же строфе: дальше вся глава оставалась двумя стенами,
    санскрит отдельно, транслитерация отдельно.

    Оставляем последний: в 10-й главе верен именно он.
    """
    out = []
    for i, b in enumerate(bs):
        nxt = bs[i + 1] if i + 1 < len(bs) else None
        if (b.get('t') and TITLE.match(b['t'])
                and nxt is not None and nxt.get('t') and TITLE.match(nxt['t'])):
            continue
        out.append(b)
    return out


def recolour(bs):
    """Санскрит «Тантрасары» — зелёный, как и на /ksh/pv/.

    На соседней странице зелёным набран санскрит самого Абхинавагупты, а
    красноватым — исходные строфы писания, которое он толкует. «Тантрасара» —
    его собственная от первой строки до последней, толковать в ней нечего, и
    зелёный говорит об этом читателю, который пришёл сюда с /ksh/pv/.

    У источника она набрана тем же цветом, что там исходные строфы, — но
    различия там и нет: класс `unicodesfontgreen` заведён ради страниц, где
    рядом стоят два разных текста. Здесь такой страницы нет ни одной.
    """
    for b in bs:
        if b['k'] == 'deva-red':
            b['k'] = 'deva'
    return bs


def blocks(pid, here=HERE):
    """Блоки главы: глава, а не глава со «Вступлением» перед ней.

    У источника каждой из двадцати двух глав предпослано одно и то же
    вступление переводчика: первая строка называет номер главы, остальные
    четыре абзаца слово в слово одинаковы. Двадцать два раза класть их в
    поисковый указатель незачем — вступление стоит один раз на
    /ksh/tantrasara/, откуда оно и взято.

    Режем по второму заголовку: первый — «Вступление», второй — «Глава N».

    Функцией модуля, а не только методом: по этим же номерам блоков считает
    словарь (`words.py`), и считать он обязан ровно то, что попадёт на
    страницу. Разойдись обрезка — и якорь встал бы не в тот абзац.
    """
    path = os.path.join(here, 'blocks', '%s.json' % pid)
    bs = json.load(open(path, encoding='utf-8'))['blocks']
    heads = [i for i, b in enumerate(bs) if b['k'] in ('h3', 'h4')]
    return recolour(dedup_title(bs[heads[1]:] if len(heads) > 1 else bs))


class TS(Book):
    key = 'tantrasara'
    name = 'Tantrasāra'
    parts = PARTS
    src = SRC
    src_url = SRC_URL
    home_name = 'Оглавление'

    def __init__(self, here=HERE):
        Book.__init__(self, here)
        # Внутри, а не наверху модуля: `words` читает блоки главы этим же
        # файлом, и встречный `import` наверху замкнул бы круг.
        import words
        self.words = words.index()
        self.marks = words.anchors()

    def link(self, word):
        """Санскритское слово в подстрочнике — ссылка на статью словаря.

        Слово стоит в падеже, и статью ему подбирает `words.find`. Чего в
        словаре нет — остаётся простым текстом: сто сорок четыре статьи на
        восемь с половиной тысяч помет, и большая их часть — служебные слова.
        """
        import words
        term = words.find(word, self.words)
        return GLOSSARY + '#t-' + words.keyof(term) if term else None

    def anchors(self, pid):
        return self.marks.get(pid, {})

    def page_title(self, name):
        # Названия глав — санскритские, и строчными их писать нельзя:
        # «śāmbhavopāyaprakāśanam» вместо «Śāmbhavopāyaprakāśanam».
        return '%s: %s' % (self.name, name)

    def blocks(self, pid):
        return blocks(pid, self.here)

    def load(self, pid):
        # Кириллица в блоке — и есть признак перевода: у источника он уже
        # русский. Проверять больше нечего, и придумывать нечего тоже.
        def tr(i, b):
            t = b.get('t', '')
            return t if CYR.search(t) else None
        return tr

    def item(self, pid, i, j, text):
        return text if CYR.search(text) else None

    def table(self, pid, i, html):
        return '<table>%s</table>' % html

    def crumbs(self):
        return ' · [Словарь терминов](%s)' % GLOSSARY

    def heading(self, tag, title, anchor):
        """Заголовка раздела на странице главы нет.

        Раздел на ней один, и назван он у источника «Глава N» — ровно тем же,
        чем названа сама страница. Второй такой заголовок под первым читается
        как сбой вёрстки. Якоря он тоже не держит: ссылки ведут на санскрит и
        на перевод, а не на заголовок над ними.
        """
        return ''

    def nav(self, secs, titles):
        """Прыжок к переводу, а не оглавление страницы.

        Раздел на странице главы один — «Вступление» отрезано, — и обычное
        оглавление из одной строки выглядело бы издевательством. Прыжок при
        этом нужен: сперва идёт вся глава на санскрите, и в двадцатой главе
        это две дюжины строф, которые пришлось бы листать до перевода.
        """
        if not secs or secs[0]['ru'] is None:
            return ''
        s = secs[0]
        links = [('санскрит', 'sa'), ('транслитерацию', 'iast'), ('перевод', 'ru')]
        row = ' · '.join('[%s](#%s-%s)' % (name, s['id'], key)
                         for name, key in links if s[key] is not None)
        return '<p class="pv-nav nosearch" markdown="1">Сразу на %s</p>' % row

    def todo(self, n):
        return ('<p class="pv-todo">У источника %d %s этой главы %s по-английски — '
                'так они здесь и стоят, в рамке. Санскрит и транслитерация на месте.</p>'
                % (n, plural(n, 'абзац', 'абзаца', 'абзацев'),
                   plural(n, 'остался', 'остались', 'остались')))

    def footer(self, pid, name):
        return ('*Перевод с санскрита, пояснения и весь санскритский аппарат принадлежат'
                ' **Габриэлю Pradīpaka** и перенесены с его сайта без изменений:'
                ' [%s](%s). За точным смыслом идите в источник.*' % (name, self.at_source(pid)))
