def occurrences():
    """Сколько раз термин помечен при каждой строфе.

    Возвращает {термин: {(номер главы, номер строфы): сколько раз}}. Номер
    строфы берётся из ключа перевода («21/2» — второй абзац под строфой 21):
    по нему же строфа зовётся и на странице.

    Заголовок главы и её колофон лежат под ключом «0/…» — у них своей строфы
    нет, и якоря тоже; такие абзацы в счёт не идут.
    """
    tables = index()
    out = hits()
    for path in sorted(glob.glob(os.path.join(HERE, 'ru', '*.json'))):
        chapter = int(os.path.splitext(os.path.basename(path))[0])
        for key, text in json.load(open(path, encoding='utf-8')).items():
            if not isinstance(text, str) or key.endswith('/html'):
                continue
            verse = key.split('/')[0]
            if not verse.isdigit() or verse == '0':
                continue
            count(out, text, (chapter, int(verse)), tables)
    return out


def links():
    """Ссылки словаря в текст: {термин: [(адрес главы, якорь строфы)]}.

    Якорей заводить не пришлось: `verse_id` в book.py уже ставит каждой строфе
    её номер (`#v23`), и словарь ссылается прямо туда.
    """
    return {iast: [('ch%d' % chapter, 'v%d' % verse)
                   for chapter, verse in places]
            for iast, places in targets(occurrences()).items()}


