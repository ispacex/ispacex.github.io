#!/usr/bin/env python3
"""Разбирает 23 страницы источника в blocks/<номер главы>.json.

Вёрстка у Габриэля Pradīpaka одна на все писания, и разбор её общий
(`common/parse.py`). Здесь остаётся то, что относится к этой тантре, и этого
четыре вещи.

**Строфа и её транслитерация стоят в одном абзаце** — как у
[Śivastotrāvalī](../sv/README.md) и не как у Parātrīśikāvivaraṇa, где они лежат
двумя стенами. Абзац разводится надвое (`common.parse.split`), чтобы `pairing`
собрал его обратно уже построчно.

**Вступление переводчика к главе в блоки не идёт.** Оно у всех двадцати трёх
глав одно и то же слово в слово — четыре абзаца о том, что скобки и двойные
дефисы принадлежат ему, — и лежать в поисковом указателе двадцать три раза не
должно. Стоит оно один раз, на [/ksh/mv/](../../ksh/mv/index.md). Режем по
заголовку «Chapter N»: до него вступление, после — глава.

**Под строфой у источника чаще всего пусто.** Изложение написано только для
глав 1–4; в главах 5–23 под каждой строфой стоит «Untranslated yet», и таких
пометок 1062 — то же, что и у Śivastotrāvalī. Сама пометка в блоки не идёт (показывать её нечего), но место
под ней остаётся: блок вида `gap`.

**Ключ перевода — номер строфы и номер абзаца под нею**, «21/2», а не
порядковый номер блока. Под одной строфой у Габриэля стоит сперва перевод её
слово в слово, потом одно-три пояснения, и звать их «первым» и «вторым» под
своей строфой можно, а сквозной номер блока съехал бы весь от одной правки
источника — а источник этот живой: главы 5–23 автор ещё переводит.

Номер строфы берётся из транслитерации, а не из деванагари над ней, где он
набран индийскими цифрами. Строфы у источника собраны в группы по одной-восьми,
и группа зовётся по **первой** своей строфе: «Mālinīvijayottaratantra 1.2»
попадёт в группу 2–5, а не мимо неё.

Строфой главы при этом считается не всё, что похоже на строфу: см. `chapter`.
"""
import json, os, re, sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
sys.path.insert(0, HERE)

from common.parse import parse, split
from parts import CHAPTERS, PARTS

# Заголовок, с которого начинается сама глава: до него — вступление.
CHAPTER = re.compile(r'^Chapter \d+$')
# Сколько строф в главе — по слову самого источника, во вступлении к ней.
# Число это в блоки не идёт, а идёт в заголовок файла: `check.py` сличает с ним
# то, что вышло из разбора. Половина строфы у источника считается («35.5»):
# главы кончаются на полустрофе, и вторая её половина открывает следующую.
COUNT = re.compile(r'chapter consists of ([\d.]+) stanzas')
# Пометка источника «строфа ещё не изложена по-английски». Полужирный к этому
# моменту уже стал звёздочками markdown.
GAP = re.compile(r'^\*\*Untranslated yet\*\*$')
# Номер строфы в транслитерации: «||21||».
NUM = re.compile(r'\|\|(\d+)\|\|')
# Он же с описки: одна черта слева вместо двух. У источника такое есть — в
# 19-й главе «…dṛḍhavrataḥ|20||», — и обходится оно дорого: номер не найден,
# счёт строф обрывается на 19-й, и все восемьдесят две оставшиеся строфы главы
# остаются без номера и без якоря. Берётся эта черта только тогда, когда двух
# нет вовсе, и разбор о ней говорит вслух: молчать о описке источника нельзя.
LOOSE = re.compile(r'\|(\d+)\|\|')
# Он же на деванагари: «॥१९८॥». Нужен там, где строфа и транслитерация лежат
# двумя стенами, а не одним абзацем, — в главе 2 такой кусок есть.
DNUM = re.compile(r'॥([०-९]+)॥')
DIGITS = {c: str(i) for i, c in enumerate('०१२३४५६७८९')}

LAT = re.compile(r'[A-Za-zÀ-ɏḀ-ỿ]')
DEVA = re.compile(r'[ऀ-ॿ]')


def prose(t):
    """Абзац прозы, в котором приведена строка на деванагари, — не строфа.

    Разбор смотрит на письменность и зовёт деванагари деванагари: у Габриэля
    попадаются пояснения, внутри которых он приводит слова Джаяратхи или Вьясы
    в подлиннике, и целый абзац английской прозы уходил бы на страницу
    санскритом — то есть не переводился бы вовсе. Решает, чего в абзаце
    больше: латиницы или деванагари. Сама мантра, набранная одним деванагари,
    остаётся санскритом.
    """
    return len(LAT.findall(t)) > len(DEVA.findall(t))


def digits(t):
    """Номера строф из деванагари: «॥१९८॥» -> 198."""
    return [int(''.join(DIGITS[c] for c in m)) for m in DNUM.findall(t)]

# Ключ для того, что стоит до первой строфы: заголовок главы на деванагари и
# перевод этого заголовка. Своего номера у них нет, а перевод у них есть.
HEAD = '0'


def key(b):
    """Ключ перевода блока: «21/2» — второй абзац под строфой 21."""
    return '%s/%d' % (b['n'], b['i']) if b.get('n') and b.get('i') else None


def keys(b):
    """Ключи перевода, которых ждёт блок.

    У абзаца он один, у списка — по одному на пункт, у таблицы — со словом
    `html`: таблица переводится целиком, своей же вёрсткой. Считать блоки
    вместо ключей нельзя — глава со списком из семи пунктов оказалась бы
    переведённой на седьмую часть.
    """
    k = key(b)
    if not k:
        return []
    if b['k'] == 'list':
        return ['%s/%d' % (k, j + 1) for j in range(len(b['items']))]
    if b['k'] == 'table':
        return ['%s/html' % k]
    return [k]


def cut(bs):
    """Блоки страницы без вступления переводчика: от заголовка «Chapter N»."""
    for i, b in enumerate(bs):
        if b['k'] in ('h3', 'h4') and CHAPTER.match(b.get('t', '')):
            return bs[i:]
    return bs


def declared(bs):
    """Сколько строф в главе объявил источник, или 0."""
    for b in bs:
        m = COUNT.search(b.get('t', ''))
        if m:
            return float(m.group(1))
    return 0


def chapter(bs):
    """Блоки главы: строфы разведены надвое, у абзацев проставлены ключи.

    Своя строфа главы узнаётся по тому, что её номер продолжает счёт: группа
    начинается ровно там, где кончилась предыдущая. Это не придирка — на
    странице стоят и **чужие** строфы: в пояснениях Габриэль приводит целиком
    то «Тантралоку», то «Йогасутры», и такая цитата набрана той же вёрсткой,
    что и сама тантра. Считать её строфой главы нельзя вдвойне: у неё свой
    номер, и однажды приняв «॥१९८॥» посреди второй главы, разбор отверг бы
    затем все настоящие строфы с 41-й по 60-ю — их номера пошли бы назад.

    Цитата остаётся санскритом на своём месте, но ни номера, ни якоря не
    получает и счёта абзацев под строфой не сбивает: пояснение, внутри
    которого она стоит, продолжается после неё.
    """
    out, at, seen, nth, whole, blind = [], HEAD, 0, 0, 0, 0
    slips = []

    def own(nums):
        """Продолжает ли эта группа счёт строф главы."""
        return bool(nums) and nums[0] == seen + 1

    def count(t):
        """Номера строф в транслитерации, с оглядкой на описку источника."""
        nums = [int(x) for x in NUM.findall(t)]
        if own(nums):
            return nums
        loose = [int(x) for x in LOOSE.findall(t)]
        if own(loose):
            slips.append(loose[0])
            return loose
        return nums

    for b in bs:
        if b['k'] in ('deva', 'deva-red'):
            pair = split(b)
            if pair is None:
                if prose(b['t']):
                    # Не строфа, а пояснение с цитатой в подлиннике: его надо
                    # переводить, как всякую прозу.
                    nth += 1
                    out.append(dict(b, k='text', n=at, i=nth))
                    continue
                # Строфа без своей транслитерации: в главе 2 есть кусок,
                # выложенный двумя стенами, как у Parātrīśikāvivaraṇa. Стены
                # сложит `pairing`; здесь остаётся взять номер с деванагари.
                nums = digits(b['t'])
                if own(nums):
                    at, seen, nth = str(nums[0]), nums[-1], 0
                    b = dict(b, n=at, to=str(nums[-1]))
                blind += 1
                out.append(b)
                continue
            sa, ia = pair
            nums = count(ia['t'])
            if own(nums):
                at, seen, nth = str(nums[0]), nums[-1], 0
                sa['n'], sa['to'] = at, str(nums[-1])
            whole += 1
            out.extend((sa, ia))
            continue
        if b['k'] in ('text', 'list', 'table'):
            nth += 1
            if b['k'] == 'text' and GAP.match(b['t']):
                out.append({'k': 'gap', 't': '', 'n': at, 'i': nth})
                continue
            out.append(dict(b, n=at, i=nth))
            continue
        out.append(b)
    return out, whole, blind, slips


def convert():
    os.makedirs(os.path.join(HERE, 'blocks'), exist_ok=True)
    titles = {pid: title for pid, _, title in PARTS}
    for node, n, _, _ in CHAPTERS:
        page = parse(os.path.join(HERE, 'src', 'en%s.html' % node))
        bs, whole, blind, slips = chapter(cut(page['blocks']))
        if blind:
            print('%2d: строф, не разведённых надвое: %d' % (n, blind))
        if slips:
            print('%2d: номер строфы набран у источника одной чертой: %s'
                  % (n, ', '.join(str(x) for x in slips)))
        json.dump({'title': titles[str(n)], 'stanzas': declared(page['blocks']),
                   'blocks': bs},
                  open(os.path.join(HERE, 'blocks', '%d.json' % n), 'w', encoding='utf-8'),
                  ensure_ascii=False, indent=1)
        gaps = sum(1 for b in bs if b['k'] == 'gap')
        print('%2d: строф %4d, без изложения у источника %4d, блоков %4d %s'
              % (n, whole, gaps, len(bs), Counter(b['k'] for b in bs)))


if __name__ == '__main__':
    convert()
