#!/usr/bin/env python3
"""Собирает ru/common.json: повторяющиеся вставки переводятся один раз.

Ключом служит сам английский текст, но набирать его заново нельзя — опечатка
тихо оставит абзац непереведённым. Поэтому блок ищется по началу строки среди
уже разобранных, а ключом становится найденный текст целиком.
"""
import json, glob, os, sys

RU = {
 'Introduction': 'Введение',
 'Further Information': 'Дополнительные сведения',

 'Read Parātrīśikāvivaraṇa':
   'Читайте Parātrīśikāvivaraṇa и переживайте Высшую Ānanda, или Божественное Блаженство, дорогой Śiva.',

 '**Important:**':
   '**Важно:** всё, что в переводе стоит в скобках и набрано курсивом, добавлено мной, '
   'чтобы завершить смысл той или иной фразы. А всё, что стоит между двойными дефисами '
   '(--...--), — это поясняющие сведения, тоже добавленные мной.',

 'I will write a "global long explanation"':
   'Под переводом я буду писать «сплошное длинное пояснение»: если, как обычно, '
   'пользоваться отдельными «примечаниями», примечаний окажется столько, что работать с '
   'ними станет невозможно. К тому же запрограммировать такое количество примечаний, одно '
   'за другим, отняло бы уйму времени. Этим «сплошным длинным пояснением» я постараюсь '
   'сделать текст настолько понятным обычному читателю, насколько сумею!',

 'Of course, I will also insert':
   'Разумеется, я буду приводить и сами исходные строфы, которые Абхинавагупта '
   'комментирует. Под переводом я буду писать «сплошное длинное пояснение»: если, как '
   'обычно, пользоваться отдельными «примечаниями», примечаний окажется столько, что '
   'работать с ними станет невозможно. К тому же запрограммировать такое количество '
   'примечаний, одно за другим, отняло бы уйму времени. Этим «сплошным длинным пояснением» '
   'я постараюсь сделать текст настолько понятным обычному читателю, насколько сумею!',

 "Abhinavagupta's _Sanskrit_ will be in dark green color while":
   'Санскрит Абхинавагупты набран зелёным, а исходные строфы Шивы и Шакти — красноватым. '
   'Ниже та же строфа идёт в транслитерации IAST, курсивом. Перевод — и строф, и '
   'комментария — отбит вертикальной чертой слева; в скобках при каждом русском слове '
   'стоит санскритское, к которому оно относится.',

 "Abhinavagupta's _Sanskrit_ will be in dark green color. In turn":
   'Санскрит Абхинавагупты набран зелёным, ниже та же строфа идёт в транслитерации IAST, '
   'курсивом. Перевод отбит вертикальной чертой слева; в скобках при каждом русском слове '
   'стоит санскритское, к которому оно относится.',

 '**Without notes of explanation yet**':
   '**Пояснений пока нет**',

 '**Without a global long explanation yet**':
   '**Сплошного длинного пояснения пока нет**',
}

texts = set()
for f in glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'blocks', '*.json')):
    for b in json.load(open(f, encoding='utf-8'))['blocks']:
        if b['k'] in ('text', 'h3', 'h4'):
            texts.add(b['t'])

EXACT = {'Introduction', 'Further Information', '**Without notes of explanation yet**',
         '**Without a global long explanation yet**'}

out, misses = {}, []
for pref, ru in RU.items():
    hit = [t for t in texts if t == pref] if pref in EXACT else \
          [t for t in texts if t.startswith(pref)]
    if not hit:
        misses.append(pref); continue
    for t in hit:
        out[t] = ru

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ru', 'common.json')
json.dump(out, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('в common.json записей:', len(out))
if misses:
    print('НЕ НАЙДЕНО:', misses)
