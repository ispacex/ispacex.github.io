#!/usr/bin/env python3
"""Общее у словарей раздела КШ: статья, основа слова, ключ, счёт мест.

Словарей на сайте четыре, и устроены они одинаково: список статей, сличение
падежных форм с основами, и расчёт того, где термин разбирается гуще всего.
Разное у них — только откуда берётся текст, по которому считать:

* `/ksh/pv/` — из `tools/pv/ru/*.json`, по номеру блока;
* `/ksh/sv/` — из `tools/sv/{ru,sa}/*.json`, по номеру строфы;
* `/ksh/ta/` — прямо из разбора страниц источника, по номеру группы строф;
* `/ksh/tantrasara/` — оттуда же, по номеру блока главы.

Список статей у последних двух общий: «Тантрасара» — та же «Тантралока», сжатая
самим Абхинавагуптой, и слова у них одни. Он лежит в `tools/trika/words.py`.

Поэтому `occurrences()` у каждого свой, а всё, что до и после, — здесь.

Отдельно стоит сказать, почему сличаются основы, а не написания. Слово в
подстрочнике стоит в падеже: `śaktiḥ`, `bhedena`, `tattvāni`, `nātham`. Правило
`stem()` снимает окончание, и оно грубое — потому и служит только подспорьем:
там, где оно не берёт (`ātmanaḥ`, `manaḥ`, `vapuḥ`), у статьи стоит прямой
список форм, и он перебивает правило.
"""
import collections
import re
import unicodedata

Term = collections.namedtuple('Term', 'iast deva ru gloss forms alias say key')


def t(iast, deva, ru, gloss, forms='', alias='', say='', key=''):
    """Статья словаря.

    `iast`  — написание латиницей, оно же основа для ключа;
    `deva`  — деванагари: по нему делается озвучка, а не по транслитерации;
    `ru`    — как термин зовётся по-русски; заодно и запрос для фильтра;
    `gloss` — краткое рабочее толкование;
    `forms` — падежные формы, которых не берёт правило;
    `alias` — чем термин ищется, если русское имя свёртке не годится;
    `say`   — написание для браузерного синтеза, если по IAST он врёт;
    `key`   — свой ключ вместо выведенного из `iast`.

    Ключ выводится из написания со снятой диакритикой, и в санскрите этого
    иногда не хватает: `kalā` (доля пути) и `kāla` (время) — разные слова,
    различаемые одной долготой, а ключ у них выходит один. Тогда ключ задаётся
    руками; проверка на совпадение в `index()` про это и напоминает.
    """
    return Term(iast, deva, ru, gloss, tuple(forms.split()), alias, say, key)


# Окончания, которые снимаются при сличении. Порядок значим: длинное раньше
# короткого, иначе `asya` потеряет только `ā`.
END = ('ābhyām', 'ānām', 'asya', 'eṣu', 'ebhyaḥ', 'ayaḥ', 'ayā', 'āni', 'ena',
       'eṇa', 'aḥ', 'āḥ', 'am', 'ām', 'āt', 'au', 'e', 'ā', 'ḥ', 'ṁ', 'ṃ')

# Санскритская помета в скобке внутри русского абзаца — та же, что разбирает
# `gloss()` в common/page.py. Здесь она нужна только чтобы считать вхождения.
GLOSS = re.compile(r'\(([^()]*?)\)')

# Помета бывает составной: `bhakti-rasa-āsava-vara-unmadāḥ`. Ссылку такое слово
# не получает — подстрочник сличает помету целиком, — но при счёте «где термин
# разбирается» части считаются наравне: в стихах, да и у Абхинавагупты, понятия
# чаще всего стоят именно внутри составных слов.
PART = re.compile(r'[-\s.]+')

# Больше трёх ссылок в строке словаря — уже не подсказка, а список.
PLACES = 3


def stem(w):
    """Основа слова: снимаем падежное окончание и конечное «a»."""
    w = w.strip().lower().replace('-', '').replace('ṃ', 'ṁ')
    for e in END:
        if w.endswith(e) and len(w) - len(e) >= 3:
            w = w[:-len(e)]
            break
    return w[:-1] if len(w) > 3 and w[-1] in 'aā' else w


def slug(iast):
    """Ключ статьи: якорь на странице словаря, он же имя файла с озвучкой.

    Тот же приём, что в словаре «Натьяшастры»: диакритика снимается, `ś` и `ṣ`
    становятся `sh` и `s`. Ключ обязан быть латиницей без знаков — он уходит и
    в имя файла, и в адрес.
    """
    s = iast.replace('ś', 'sh').replace('Ś', 'sh').replace('ñ', 'n')
    s = unicodedata.normalize('NFD', s.lower())
    return re.sub(r'[^a-z]', '', s)


def keyof(term):
    """Ключ статьи: свой, если задан, иначе выведенный из написания."""
    return term.key or slug(term.iast)


def terms(sections):
    for _, group in sections:
        for term in group:
            yield term


def index(sections):
    """Слово из текста → статья словаря: (по формам, по основам).

    Сначала прямые формы, потом основы: прямой список должен перебивать
    правило, а не наоборот. Совпадение ключей или основ у двух статей — ошибка
    сборки: одна звучала бы голосом другой, а ссылка вела бы не туда, и молча.
    """
    by_form, by_stem, keys = {}, {}, {}
    for term in terms(sections):
        key = keyof(term)
        if key in keys:
            raise SystemExit('ключ совпал: %s и %s' % (keys[key], term.iast))
        keys[key] = term.iast
        for w in (term.iast,) + term.forms:
            w = w.lower().replace('-', '')
            # Одна и та же форма у двух статей — тоже тихая ошибка: побеждала
            # бы та, что записана позже, и ссылка из текста вела бы не туда.
            # Так `āṇava` разом просилась и в путь, и в первую грязь.
            if w in by_form and by_form[w] is not term:
                raise SystemExit('форма «%s» у двух статей: %s и %s'
                                 % (w, by_form[w].iast, term.iast))
            by_form[w] = term
        s = stem(term.iast)
        if s in by_stem and by_stem[s] is not term:
            raise SystemExit('основы совпали: %s и %s' % (by_stem[s].iast, term.iast))
        by_stem[s] = term
    return by_form, by_stem


def find(word, tables):
    """Статья для санскритского слова из подстрочника, или None."""
    by_form, by_stem = tables
    w = word.strip().lower().replace('-', '')
    return by_form.get(w) or by_stem.get(stem(word))


def count(hits, text, where, tables, parts=True):
    """Считает пометы одного абзаца в `hits[термин][where]`.

    Сперва помета целиком — составной термин («parama-īśvara») обязан достаться
    себе, а не своей половине; не нашлось — разбираем на части.

    `parts=False` разбора на части не делает: считается только помета целиком.
    Так считает Parātrīśikāvivaraṇa — не потому, что так лучше, а потому, что
    так там было до того, как этот счёт стал общим. Разбор на части сдвинул бы
    её якоря, а якорь — это адрес, по которому на страницу уже ссылаются.
    """
    for m in GLOSS.finditer(text):
        whole = find(m.group(1), tables)
        for part in [m.group(1)] if whole or not parts else PART.split(m.group(1)):
            term = find(part, tables)
            if term is not None:
                hits[term.iast][where] += 1


def hits():
    return collections.defaultdict(collections.Counter)


def targets(occurrences, places=PLACES):
    """Куда словарь ссылается: до трёх мест на термин.

    Вход — {термин: {(страница, место): сколько раз}}. Берутся места, где
    термин помечен гуще всего: там его и разбирают, а не поминают мимоходом.
    При равном счёте вперёд идёт то, что раньше в книге.

    С одной страницы берётся одно место. Иначе в строке словаря стояли бы три
    ссылки, которые читатель между собою не различит: подписью им служит номер,
    а номер у них почти один и тот же.
    """
    out = {}
    for iast, where in occurrences.items():
        best = {}
        for (page, spot), n in where.items():
            if best.get(page, (0,))[0] < n:
                best[page] = (n, spot)
        top = sorted(best.items(), key=lambda kv: (-kv[1][0], kv[0]))[:places]
        out[iast] = sorted((page, spot) for page, (_n, spot) in top)
    return out
