def occurrences(got=None):
    """Сколько раз термин помечен в переводе каждой группы строф.

    Возвращает {термин: {(глава, первая строфа группы): сколько раз}}. Ключ —
    тот же, которым абзац перевода зовётся на странице: `t<глава>.<строфа>`
    (см. `tr_html` в build-ta.py).

    Перевод берётся прямо из разбора страниц источника: своего `ru/*.json` у
    этого конвейера нет — переводить здесь нечего, текст готовый.
    """
    if got is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            'ta_ru', os.path.join(HERE, 'ta-ru.py'))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        got = mod.collect()
    tables = index()
    out = hits()
    for ch in got:
        for g in got[ch]['groups']:
            if not g['nums']:
                continue
            where = (ch, g['nums'][0])
            for text in g['ru']:
                count(out, text, where, tables)
    return out


GLOSSARY = '/ksh/ta/glossary/'

_TABLES = None


def link(word):
    """Санскритское слово в подстрочнике — ссылка на статью словаря, или None.

    Слово стоит в падеже, и статью ему подбирает `find`. Чего в словаре нет —
    остаётся простым текстом: сто двадцать статей на сорок шесть тысяч помет, и
    большая их часть — служебные слова.

    Таблицы считаются один раз: сборка зовёт это на каждое слово, а глав
    тридцать семь.
    """
    global _TABLES
    if _TABLES is None:
        _TABLES = index()
    term = find(word, _TABLES)
    return GLOSSARY + '#t-' + keyof(term) if term else None


def links(got=None):
    """Ссылки словаря в текст: {термин: [(адрес главы, якорь абзаца)]}."""
    return {iast: [('ch%d' % ch, 't%d.%d' % (ch, n)) for ch, n in places]
            for iast, places in targets(occurrences(got)).items()}


